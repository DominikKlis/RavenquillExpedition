local ADDON, ns = ...

ns.Locales = ns.Locales or {}
ns.missingL = ns.missingL or {}

local function ClientLocale()
  if type(GetLocale) ~= "function" then return "enUS" end
  local ok, loc = pcall(GetLocale)
  if ok and type(loc) == "string" and not (issecretvalue and issecretvalue(loc)) then return loc end
  return "enUS"
end
ns.locale = ClientLocale()

function ns.LGet(key)
  local t = ns.Locales[ns.locale]
  local v = t and t[key]
  if v == nil then v = ns.Locales.enUS and ns.Locales.enUS[key] end
  return v
end

ns.L = setmetatable({}, { __index = function(_, key)
  local v = ns.LGet(key)
  if v == nil then
    ns.missingL[key] = true
    return tostring(key)
  end
  return v
end })

function ns.G(name, key)
  local v = _G[name]
  if type(v) == "string" and v ~= "" and not (issecretvalue and issecretvalue(v)) then return v end
  return ns.L[key or name]
end


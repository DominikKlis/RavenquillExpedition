-- Generates the recipe data for all five gear professions (plan G2 / G7.4, G7.7, G7.12) and the enchant table
-- (G4 / G7.2, G7.7, G7.14). Replaces the old regex generator dev/gen_recipes.py.
-- Run from the addon folder:
--   lua dev/gen_recipes.lua [CraftersJournal Data dir] [SimGear unzip dir]
-- Writes Data/Leatherworking.lua, Data/Blacksmithing.lua, Data/Tailoring.lua, Data/Engineering.lua,
-- Data/Enchanting.lua (items the profession makes) and Data/Enchants.lua (enchants = SimGear ∩ CraftersJournal).
-- Both sources are loaded as DATA in a sandbox (loadfile with an empty private env, mode "t").
--
-- Row filter (explicit, G7.4): negative recipe IDs (Enchanting's shard conversions) are skipped,
-- `intermediate = true` rows are skipped, rows without `out` are items for nobody except Enchanting
-- (those are the enchants). Row counts are asserted per profession; a changed source fails loudly.
local P = dofile((arg[0]:gsub("[^/\\]*$", "")) .. "paths.lua")
local ROOT = P.ROOT
local function argv(i) return arg[i] ~= "" and arg[i] or nil end
local CJ = assert(P.CraftersJournal(argv(1)), "CraftersJournal's Data folder not found: pass it as argument 1 or set RQ_CRAFTERSJOURNAL")
local SG = assert(P.SimGear(argv(2)), "SimGear Forever not found: pass it as argument 2, set RQ_SIMGEAR or unzip it into <repo>/.cache/simgear/")
local OUT = argv(3) or ROOT -- tests point this at a scratch folder

-- name, skill line, expected non-intermediate rows with a non-negative ID, expected rows with `out`
local PROFS = {
  { "Leatherworking", 165, 501, 501 },
  { "Blacksmithing", 164, 438, 438 },
  { "Tailoring", 197, 398, 398 },
  { "Engineering", 202, 251, 251 }, -- incl. Goblin "Boom" Box (the old regex dropped it, G7.4)
  { "Enchanting", 333, 240, 62 },   -- 62 make items; the other 178 are enchants
}
local EXPECT_ENCHANTS = { rows = 175, stats = 122, damage = 10, utility = 27, proc = 16 } -- checked below

local function q(s) return string.format("%q", s) end

local function sandbox(path, ...)
  local chunk = assert(loadfile(path, "t", {}))
  chunk(...)
end

local function skillOf(r)
  -- same rule as the old generator: trainer skill, 1 for basic recipes, else the orange value of t
  if r.train then return r.train end
  if r.basic then return 1 end
  return r.t and r.t[2] or 0
end
local function srcOf(r)
  if r.fee or r.basic or r.trainer then return "trainer" end
  if r.scroll then return "pattern" end
  return "other"
end
local function reagents(r)
  local parts = {}
  for _, x in ipairs(r.r or {}) do parts[#parts + 1] = string.format("{%d,%d}", x[1], x[2]) end
  return "{ " .. table.concat(parts, ", ") .. " }"
end
local function sortedIDs(t)
  local ids = {}
  for id in pairs(t) do ids[#ids + 1] = id end
  table.sort(ids)
  return ids
end

local report, cjEnchants = {}, nil
for _, p in ipairs(PROFS) do
  local name, skillLine, expectRows, expectOut = p[1], p[2], p[3], p[4]
  local ES = {}
  sandbox(CJ .. name .. ".lua", "CraftersJournal", ES)
  local D = assert(ES.Data and ES.Data[name], name .. ": no ES.Data." .. name)
  assert(D.skillLine == skillLine, name .. ": skill line " .. tostring(D.skillLine) .. " ~= " .. skillLine)
  local rows, enchants, skipped = {}, {}, { negative = 0, intermediate = 0 }
  local n, nOut = 0, 0
  for id, r in pairs(D.recipes) do
    if id < 0 then skipped.negative = skipped.negative + 1
    elseif r.intermediate then skipped.intermediate = skipped.intermediate + 1
    else
      n = n + 1
      if r.out then nOut = nOut + 1; rows[id] = r
      else
        assert(name == "Enchanting", name .. " recipe " .. id .. " has no `out`")
        enchants[id] = r
      end
    end
  end
  assert(n == expectRows, ("%s: %d rows, expected %d"):format(name, n, expectRows))
  assert(nOut == expectOut, ("%s: %d rows with out, expected %d"):format(name, nOut, expectOut))
  if name == "Enchanting" then cjEnchants = enchants end

  -- the same item made twice inside one profession would make itemToSpell ambiguous
  local byItem = {}
  for _, id in ipairs(sortedIDs(rows)) do
    local item = rows[id].out[1]
    assert(not byItem[item], ("%s: item %d made by %d and %d"):format(name, item, byItem[item] or 0, id))
    byItem[item] = id
  end

  local w = {}
  w[#w + 1] = ("-- %s recipes: [recipeSpellID] = { item = crafted itemID, skill = required skill, src = trainer|pattern|other, name, r = reagents, faction = only one side can learn it }"):format(name)
  w[#w + 1] = "-- GENERATED by dev/gen_recipes.lua from CraftersJournal's Data/" .. name .. ".lua (WoW Forever client data; no license file,"
  w[#w + 1] = "-- private use accepted by the user, plan G6.3). Do not edit; regenerate. Names are English fallbacks."
  w[#w + 1] = ("-- %d rows: negative IDs (conversions) and intermediate materials skipped%s."):format(nOut,
    name == "Enchanting" and "; enchants without an item are in Data/Enchants.lua" or "")
  w[#w + 1] = "local _, ns = ..."
  w[#w + 1] = "ns.Recipes = ns.Recipes or {}"
  w[#w + 1] = "ns.RecipeMeta = ns.RecipeMeta or {}"
  w[#w + 1] = ("ns.RecipeMeta.%s = { skillLine = %d, rows = %d }"):format(name, skillLine, nOut)
  w[#w + 1] = "ns.Recipes." .. name .. " = {"
  for _, id in ipairs(sortedIDs(rows)) do
    local r = rows[id]
    w[#w + 1] = ("  [%d] = { item = %d, skill = %d, src = %q, name = %s, r = %s%s },"):format(id, r.out[1], skillOf(r), srcOf(r),
      q(r.name), reagents(r), r.faction and (", faction = " .. q(r.faction)) or "")
  end
  w[#w + 1] = "}"
  local f = assert(io.open(OUT .. "Data/" .. name .. ".lua", "wb"))
  f:write(table.concat(w, "\n"), "\n")
  f:close()
  report[#report + 1] = ("%s: %d item rows (skipped %d negative, %d intermediate)"):format(name, nOut, skipped.negative, skipped.intermediate)
end

---------------------------------------------------------------------------
-- Enchants: SimGear's data/enchants.lua (MIT) ∩ CraftersJournal's enchant recipes
---------------------------------------------------------------------------
local SGns = {}
sandbox(SG .. "SimGearForever/data/enchants.lua", "SimGearForever", SGns)
local ED = SGns.EnchantData
local function kindOf(row)
  if row.proc then return "proc" end
  if row.stats and next(row.stats) then return "stats" end
  if row.damage and row.damage ~= 0 then return "damage" end
  return "utility" -- utility = true, or nothing we could score
end
local out, count, sgOnly, seen = {}, { stats = 0, damage = 0, utility = 0, proc = 0 }, {}, {}
for _, row in ipairs(ED.rows) do
  local cj = cjEnchants[row.spell]
  if not cj then sgOnly[#sgOnly + 1] = row.spell
  else
    seen[row.spell] = true
    assert(not (row.stats and next(row.stats) and row.damage), "stats AND damage on " .. row.spell)
    local kind = kindOf(row)
    count[kind] = count[kind] + 1
    out[#out + 1] = { row = row, cj = cj, kind = kind }
  end
end
local cjOnly = {}
for _, id in ipairs(sortedIDs(cjEnchants)) do if not seen[id] then cjOnly[#cjOnly + 1] = id end end
assert(#out == EXPECT_ENCHANTS.rows, "enchant rows " .. #out)
for k, v in pairs(count) do assert(v == EXPECT_ENCHANTS[k], ("enchant kind %s: %d, expected %d"):format(k, v, EXPECT_ENCHANTS[k])) end
assert(table.concat(sgOnly, ",") == "1217203", "SimGear-only enchants: " .. table.concat(sgOnly, ","))
assert(table.concat(cjOnly, ",") == "435481,435903,463871", "CraftersJournal-only enchants: " .. table.concat(cjOnly, ","))

-- rows sharing an enchant ID (G7.7) must describe the same effect, else "dedupe by enchant ID" is wrong
local function sig(r)
  local ks = {}
  for k, v in pairs(r.stats or {}) do ks[#ks + 1] = k .. "=" .. v end
  table.sort(ks)
  return table.concat(ks, ",") .. "|" .. tostring(r.damage) .. "|" .. tostring(r.proc) .. "|" .. tostring(r.utility)
end
local byEnchant, shared = {}, {}
for _, e in ipairs(out) do
  local id = e.row.enchant
  if byEnchant[id] then
    shared[id] = true
    assert(sig(byEnchant[id].row) == sig(e.row), "enchant " .. id .. " has two different effects")
  else byEnchant[id] = e end
end
local nShared = 0
for _ in pairs(shared) do nShared = nShared + 1 end

local function statTable(t)
  local ks = sortedIDs(t or {})
  local parts = {}
  for _, k in ipairs(ks) do parts[#parts + 1] = k .. " = " .. string.format("%.15g", t[k]) end
  return "{ " .. table.concat(parts, ", ") .. (#parts > 0 and " }" or "}")
end
local w = {}
w[#w + 1] = "-- GENERATED by dev/gen_recipes.lua. Do not edit; regenerate."
w[#w + 1] = "-- Enchants that Enchanting puts on an item: SimGear Forever's data/enchants.lua (client build " .. ED.build .. ", " .. ED.date .. ")"
w[#w + 1] = "-- intersected with CraftersJournal's Data/Enchanting.lua (skill, source, reagents). `leads`, `text`, `procInfo`,"
w[#w + 1] = "-- `formula` and `new` dropped. kind: stats (scored) | damage (weapon damage per hit: divided by the worn weapon's speed,"
w[#w + 1] = "-- plan W5) | utility | proc (never scored, never suggested, never replaced; plan G7.2)."
w[#w + 1] = "-- SimGear part: Copyright (c) 2026 Flavius and SimGear Forever contributors, MIT License (see NOTICE.txt)."
w[#w + 1] = "-- CraftersJournal part: no license file; private use accepted by the user (plan G6.3)."
w[#w + 1] = ("-- %d rows (%d stats, %d damage, %d utility, %d proc); %d enchant IDs are shared by several recipes."):format(#out,
  count.stats, count.damage, count.utility, count.proc, nShared)
w[#w + 1] = "local _, ns = ..."
w[#w + 1] = "ns.Enchants = { build = " .. q(ED.build) .. ", rows = {"
for _, e in ipairs(out) do
  local r, cj = e.row, e.cj
  local parts = { ("spell = %d, enchant = %d, name = %s, slot = %q, kind = %q"):format(r.spell, r.enchant, q(r.name), r.slot, e.kind) }
  if r.stats and next(r.stats) then parts[#parts + 1] = "stats = " .. statTable(r.stats) end
  if r.damage and r.damage ~= 0 then parts[#parts + 1] = "damage = " .. r.damage end
  parts[#parts + 1] = ("skill = %d, src = %q, r = %s"):format(skillOf(cj), srcOf(cj), reagents(cj))
  if cj.faction then parts[#parts + 1] = "faction = " .. q(cj.faction) end
  w[#w + 1] = "  { " .. table.concat(parts, ", ") .. " },"
end
w[#w + 1] = "} }"
local f = assert(io.open(OUT .. "Data/Enchants.lua", "wb"))
f:write(table.concat(w, "\n"), "\n")
f:close()
report[#report + 1] = ("Enchants: %d rows (%d stats, %d damage, %d utility, %d proc), %d shared enchant IDs; SimGear-only %s, CraftersJournal-only %s")
  :format(#out, count.stats, count.damage, count.utility, count.proc, nShared, table.concat(sgOnly, ","), table.concat(cjOnly, ","))
for _, line in ipairs(report) do io.stderr:write("gen_recipes: " .. line .. "\n") end

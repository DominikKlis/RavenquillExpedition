-- One-off tool: writes RavenquillExpedition_CraftAdvisor/dev/fixtures/gear_sets.lua from a real
-- RavenquillExpedition_CraftAdvisor SavedVariables file, anonymised (member names and crafter GUIDs replaced).
-- Usage: lua scripts/extract-gear-fixture.lua <path to RavenquillExpedition_CraftAdvisor.lua> [max sets]
-- Read the output before committing it: it must not contain player names.
local src, maxSets = arg[1], tonumber(arg[2] or "") or 8
assert(src, "usage: lua scripts/extract-gear-fixture.lua <SavedVariables file> [max sets]")
local root = (arg[0]:gsub("[^/\\]*$", "")) .. "../"
local out = root .. "RavenquillExpedition_CraftAdvisor/dev/fixtures/gear_sets.lua"

local env = {}
assert(loadfile(src, "t", env))()
local db = assert(env.RavenquillExpeditionCraftDB, "not a CraftAdvisor SavedVariables file")

local sets = {}
for _, m in pairs(db.members or {}) do
  if type(m.items) == "table" and next(m.items) then sets[#sets + 1] = m.items end
end
local function size(items) local n, b = 0, 0 for _, l in pairs(items) do n = n + 1; b = b + #l end return n * 1000 + b end
table.sort(sets, function(a, b) return size(a) > size(b) end)

local guidN, guids = 0, {}
local function anon(link)
  return (link:gsub("Player%-%d+%-%x+", function(g)
    if not guids[g] then guidN = guidN + 1; guids[g] = ("Player-1-%08X"):format(guidN) end
    return guids[g]
  end))
end

local lines = {
  "-- Generated by scripts/extract-gear-fixture.lua from a real CraftAdvisor SavedVariables file (anonymised:",
  "-- no member names, crafter GUIDs replaced). Real item links, sorted biggest set first.",
  "return {",
}
for i = 1, math.min(maxSets, #sets) do
  local slots = {}
  for slot in pairs(sets[i]) do slots[#slots + 1] = slot end
  table.sort(slots)
  lines[#lines + 1] = "  { -- set " .. i
  for _, slot in ipairs(slots) do
    lines[#lines + 1] = ("    [%d] = %q,"):format(slot, anon(sets[i][slot]))
  end
  lines[#lines + 1] = "  },"
end
lines[#lines + 1] = "}"
local f = assert(io.open(out, "wb"))
f:write(table.concat(lines, "\n"), "\n")
f:close()
print(("wrote %d sets to %s (%d crafter GUIDs replaced)"):format(math.min(maxSets, #sets), out, guidN))
